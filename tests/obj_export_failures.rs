#![cfg(feature = "obj-io")]

use csgrs::{
    GeometryCertainty, GeometryContext, Real, TriangleMesh,
    errors::{ValidationError, ValidationErrorKind},
    io::{IoError, obj},
    solid::{self, SolidExt},
};
use hyperlattice::Point3;
use hypermesh::{HypermeshError, MeshCertainty, Triangle};
use std::error::Error;

fn malformed(index: usize) -> TriangleMesh {
    TriangleMesh::new(vec![Point3::origin()], vec![Triangle::new(0, index, 0)])
}

fn assert_missing_position(error: IoError, index: usize) {
    let IoError::Construction { format, source } = error else {
        panic!("expected an OBJ construction error, got {error:?}");
    };
    assert_eq!(format, "OBJ");
    let native = HypermeshError::VertexIndexOutOfBounds {
        index,
        vertex_count: 1,
    };
    assert_eq!(source, ValidationError::Mesh(native.clone()));
    assert_eq!(source.kind(), ValidationErrorKind::InvalidInput);
    assert_eq!(
        source.source().unwrap().downcast_ref::<HypermeshError>(),
        Some(&native)
    );
    let detail = source.to_string();
    assert!(detail.contains(&index.to_string()), "{detail}");
}

#[test]
fn missing_position_is_an_export_error() {
    assert_missing_position(obj::to_obj(&malformed(1), "invalid").unwrap_err(), 1);
}

#[test]
fn largest_index_is_rejected_before_obj_index_conversion() {
    assert_missing_position(
        obj::to_obj(&malformed(usize::MAX), "invalid").unwrap_err(),
        usize::MAX,
    );
}

#[test]
fn stream_writer_preserves_the_index_diagnostic_and_existing_bytes() {
    for index in [1, usize::MAX] {
        let mut output = b"existing bytes".to_vec();
        let error = obj::write_obj(&malformed(index), &mut output, "invalid").unwrap_err();
        assert_missing_position(error, index);
        assert_eq!(output, b"existing bytes");
    }
}

#[test]
fn metadata_failure_keeps_its_existing_priority() {
    assert!(matches!(
        obj::to_obj(&malformed(1), "invalid\nname"),
        Err(IoError::InvalidMetadata {
            format: "OBJ",
            field: "object name"
        })
    ));
}

#[test]
fn coordinate_projection_failure_remains_typed_and_unwritten() {
    let mesh = TriangleMesh::new(
        vec![
            Point3::new("1e400".parse().unwrap(), Real::zero(), Real::zero()),
            Point3::new(Real::zero(), Real::one(), Real::zero()),
            Point3::new(Real::zero(), Real::zero(), Real::one()),
        ],
        vec![Triangle::new(0, 1, 2)],
    );
    let mut output = b"existing bytes".to_vec();
    assert!(matches!(
        obj::write_obj(&mesh, &mut output, "large"),
        Err(IoError::UnrepresentableCoordinate {
            format: "OBJ",
            field: "vertex x",
            target: "f64"
        })
    ));
    assert_eq!(output, b"existing bytes");
}

#[test]
fn open_triangle_keeps_its_documented_geometry_and_serialization() {
    let mesh = TriangleMesh::new(
        vec![
            Point3::origin(),
            Point3::new(Real::one(), Real::zero(), Real::zero()),
            Point3::new(Real::zero(), Real::one(), Real::zero()),
        ],
        vec![Triangle::new(0, 1, 2)],
    );
    let expected = concat!(
        "# Generated by csgrs\no triangle\n",
        "v 0.00000000000000000 0.00000000000000000 0.00000000000000000\n",
        "v 1.00000000000000000 0.00000000000000000 0.00000000000000000\n",
        "v 0.00000000000000000 1.00000000000000000 0.00000000000000000\n",
        "f 1 2 3\n"
    );
    assert_eq!(obj::to_obj(&mesh, "triangle").unwrap(), expected);
    let restored = obj::from_obj(expected.as_bytes()).unwrap();
    assert_eq!(restored.positions.as_ref(), mesh.positions.as_ref());
    assert_eq!(restored.triangles[0].indices(), [0, 1, 2]);
    let mut stream = Vec::new();
    obj::write_obj(&mesh, &mut stream, "triangle").unwrap();
    assert_eq!(stream, expected.as_bytes());
}

fn assert_unit_cube(mesh: &TriangleMesh) {
    let context = GeometryContext::STRICT.mesh_context();
    assert_eq!(
        mesh.validate_closed_pwn(&context).unwrap().certainty,
        MeshCertainty::Certified
    );
    assert!(mesh.is_closed_manifold_geometry(&context).unwrap().value);
    let zero = Real::zero();
    let one = Real::one();
    let mut six_volume = Real::zero();
    for triangle in mesh.triangles.iter() {
        let points = triangle.indices().map(|i| &mesh.positions[i]);
        for point in points {
            for coordinate in [&point.x, &point.y, &point.z] {
                assert!(coordinate == &zero || coordinate == &one);
            }
        }
        assert!((0..3).any(|axis| {
            let values = points.map(|p| [&p.x, &p.y, &p.z][axis]);
            values.iter().all(|v| *v == &zero) || values.iter().all(|v| *v == &one)
        }));
        let [a, b, c] = points.map(|p| p.to_vector());
        six_volume += a.dot(&b.cross(&c));
    }
    // Independent oriented tetrahedral volume, with all faces on the unit box.
    assert_eq!(six_volume, Real::from(6));
}

#[test]
fn empty_and_solid_outputs_reimport_and_compose() {
    let empty = solid::empty();
    let cube = solid::cube(Real::one()).unwrap();
    for original in [&empty, &cube] {
        let text = obj::to_obj(original, "model").unwrap();
        let restored =
            obj::from_obj_with_context(text.as_bytes(), &GeometryContext::STRICT).unwrap();
        assert_eq!(restored.certainty, GeometryCertainty::Certified);
        let restored = restored.value;
        if original.positions.is_empty() {
            assert!(restored.positions.is_empty() && restored.triangles.is_empty());
            assert_unit_cube(&restored.try_union(&cube).unwrap());
        } else {
            assert_unit_cube(&restored);
            assert_unit_cube(&restored.try_union(&empty).unwrap());
        }
    }
}
