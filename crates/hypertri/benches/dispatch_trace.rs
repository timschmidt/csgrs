use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::hint::black_box;

use hypertri::{
    Point2, PointD, PolygonInput, PredicatePolicy, Rational, Real, TriangulationContext,
    TriangulationOptions,
};

const STRICT: TriangulationContext = TriangulationContext::new(PredicatePolicy::STRICT);

fn trace<T>(
    name: &str,
    workload: impl FnOnce() -> hypertri::Result<T>,
) -> hyperreal::dispatch_trace::TraceSnapshot {
    hyperreal::dispatch_trace::reset();
    let value = hyperreal::dispatch_trace::with_recording(workload)
        .unwrap_or_else(|error| panic!("{name} must remain strictly certified: {error}"));
    black_box(value);
    let trace = hyperreal::dispatch_trace::take_trace();
    let correlation = trace.correlation_summary();
    assert!(
        correlation.dispatch_events > 0 || correlation.rational_temporaries > 0,
        "{name} emitted no exact-computation trace"
    );
    println!("{name}: {correlation:?}");
    trace
}

fn write_report(rows: &BTreeMap<&str, hyperreal::dispatch_trace::TraceSnapshot>) {
    if std::env::var_os("HYPERTRI_SKIP_BENCHMARK_REPORTS").is_some() {
        return;
    }

    let mut out = String::from(
        "# Hypertri Dispatch Trace\n\n\
Generated by `cargo bench --bench dispatch_trace --features all-algorithms,runtime-select,dispatch-trace`. Each workload runs once outside Criterion and must record exact dependency dispatch or rational work. Use the timing suites represented in `benchmarks.md` for performance comparisons.\n\n\
## Correlation Summary\n\n\
| Workload | Dispatch | Predicates | Linear Algebra | Exact Reducers | Approximation | Refinement | Cache | Fallback/Abort | Rational Temporaries | Rational Reductions | Rational GCDs |\n\
| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |\n",
    );
    for (name, trace) in rows {
        let summary = trace.correlation_summary();
        writeln!(
            out,
            "| `{name}` | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |",
            summary.dispatch_events,
            summary.predicate_events,
            summary.linear_algebra_events,
            summary.exact_reducer_events,
            summary.approximation_events,
            summary.refinement_events,
            summary.cache_events,
            summary.fallback_or_abort_events,
            summary.rational_temporaries,
            summary.rational_reductions,
            summary.rational_gcds,
        )
        .expect("writing a String cannot fail");
    }

    out.push_str(
        "\n## Dispatch Paths\n\n\
| Workload | Layer | Operation | Path | Count |\n\
| --- | --- | --- | --- | ---: |\n",
    );
    for (name, trace) in rows {
        for entry in &trace.dispatch {
            writeln!(
                out,
                "| `{name}` | `{}` | `{}` | `{}` | {} |",
                entry.layer, entry.operation, entry.path, entry.count,
            )
            .expect("writing a String cannot fail");
        }
    }

    fs::write("dispatch_trace.md", out).expect("dispatch trace report should be writable");
}

fn main() {
    let polygon = vec![
        Point2::new(Real::from(0), Real::from(0)),
        Point2::new(Real::from(4), Real::from(0)),
        Point2::new(Real::from(4), Real::from(4)),
        Point2::new(Real::from(2), Real::from(2)),
        Point2::new(Real::from(0), Real::from(4)),
    ];
    let earcut = trace("earcut", || hypertri::earcut(&STRICT, &polygon, &[]));

    let points = vec![
        Point2::new(Real::from(0), Real::from(0)),
        Point2::new(Real::from(3), Real::from(0)),
        Point2::new(Real::from(3), Real::from(3)),
        Point2::new(Real::from(0), Real::from(3)),
        Point2::new(Real::from(1), Real::from(2)),
    ];
    let delaunay = trace("delaunay", || hypertri::cdt::delaunay(&STRICT, &points));

    let quarter = || Real::from(Rational::fraction(1, 4).unwrap());
    let nd_points = vec![
        PointD::new(vec![Real::from(0), Real::from(0), Real::from(0)]),
        PointD::new(vec![Real::from(1), Real::from(0), Real::from(0)]),
        PointD::new(vec![Real::from(0), Real::from(1), Real::from(0)]),
        PointD::new(vec![Real::from(0), Real::from(0), Real::from(1)]),
        PointD::new(vec![quarter(), quarter(), quarter()]),
    ];
    let nd_delaunay = trace("nd_delaunay", || {
        hypertri::nd::delaunay_complex(&STRICT, &nd_points)
    });

    let input = PolygonInput::new(polygon, vec![]);
    let runtime_select = trace("runtime_select", || {
        hypertri::triangulate_polygon(&STRICT, &input, TriangulationOptions::default())
    });

    write_report(&BTreeMap::from([
        ("delaunay", delaunay),
        ("earcut", earcut),
        ("nd_delaunay", nd_delaunay),
        ("runtime_select", runtime_select),
    ]));
}
