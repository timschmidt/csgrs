sbfLn'' :: SBinFloat -> SBinFloat
sbfLn'' x = sbfLn''' (sbfSub x sbfOne)


-- Need to ensure that any number can be placed in [1/2, 3/2] by 
--   multiplying or dividing by exp(1).

-- Order is important here. The algorithm looks for cases where either 
--   x, x.e, or x/e can be confirmed to be in [1/2,3/2].

-- This function that normalisation has been performed that guarantees that
--   numbers starting (1:-1:_) or (0:_) have all been modified.

sbfLn' (_,(-1:_))        = undefined
sbfLn' x@(-1,(1:  1:_))  = sbfSub (sbfLn'' (sbfNormAllowNegExp    
				   (sbfMul x (sbfExpFn sbfOne)))) sbfOne
sbfLn' x@(0,(1:  0: a: b: c: _))  = 
       if ((a == -1) ||
	  ((a ==  0) && ((b == -1) ||
		        ((b ==  0) && (c /= 1))))) then
         sbfSub (sbfLn'' (sbfNormAllowNegExp    
				   (sbfMul x (sbfExpFn sbfOne)))) sbfOne

       else (sbfLn'' x) 
sbfLn' x@(0,(1:  1:_))  = (sbfLn'' x)  -- [1/2, 1]
sbfLn' x@(1,(1:  _))    = (sbfLn'' x)  -- [1/2,3/2]
sbfLn' x@(2,(1:  0: -1: -1: _)) = (sbfLn'' x)
sbfLn' x@(2,(1:  0: -1: 0: -1: _)) = (sbfLn'' x)
sbfLn' x@(2,(1:  0: _)) = sbfAdd (sbfLn'' (sbfNormAllowNegExp 
				   (sbfDiv x (sbfExpFn sbfOne)))) sbfOne

sbfLn' x@(e,_) | e >= 1 = sbfAdd (sbfLn' (sbfNormAllowNegExp 
				   (sbfDiv x (sbfExpFn sbfOne)))) sbfOne
 	       | e <  1 = sbfSub (sbfLn' (sbfNormAllowNegExp 
				   (xsbfMul x (sbfExpFn sbfOne)))) sbfOne


sbfLn x = sbfLn' (sbfNormAllowNegExpExtra x)
