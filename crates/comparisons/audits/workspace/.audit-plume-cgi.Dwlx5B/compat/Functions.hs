{- 
-- Exponential Function. Computed using the limit of the series
-- generated by

  s(x,0) = 1
  s(x,n) = x.s(n)/ n

Hence:
  s(x,i) = x^i/i!  

And:
  exp(x)   = Sum(i=0..inf, s(x,i))

-}


-- exp_it : Compute s(x,n) 
--          y = s(x,n-1), s(x,n) = x * s(x,n-1) / n
exp_it :: SBinFloat -> SBinFloat -> Int -> SBinFloat
exp_it x y n  = sbfIntDiv (sbfMul x y) n


-- exp_pos_bounds : Compute upper and lower bounds of 
--                  Sum(i=0..n, s(x,i)), given x > 0, s(n) <= 1
--                  Lower limit = Sum(i=0..n, s(x,i))
--                  Upper limit = Sum(i=0..n, s(x,i)) + s(x,n)
--                     y = s(x,n)
--                     t = Sum(i=0..n, s(x,i))
exp_pos_bounds :: SBinFloat -> SBinFloat -> Int -> SbInterval
exp_pos_bounds y t n = (lower, upper)
	where {lower = sbfAdd y t;
	       upper = sbfAdd y lower}



-- exp_neg_bounds : Compute upper and lower bounds of 
--                  Sum(i=0..n, s(x,i)), given x < 0
--                  This value oscillates round the limit
--                     y = s(x,n)
--                     t = Sum(i=0..n, s(x,i))
exp_neg_bounds :: SBinFloat -> SBinFloat -> Int -> SbInterval
exp_neg_bounds y t n | odd n    = (t', t)
		     | otherwise = (t,  t')
	where t'  = sbfAdd y t;



-- exp_uk_bounds : Compute upper and lower bounds of 
--                  Sum(i=0..n, s(x,i)), given, s(n) <= 1
--                  Limits union of exp_neg_bounds and exp_pos_bounds.
--                     y = s(x,n)
--                     t = Sum(i=0..n, s(x,i))
exp_uk_bounds :: SBinFloat -> SBinFloat -> Int -> (SbInterval, SBinFloat)
exp_uk_bounds y t n = ((sbfMin t (sbfMin t' t''), sbfMax t (sbfMax t' t'')),t')
	where {t'  = sbfAdd y t;
	       t'' = sbfAdd y t'}



-- exp_elt1 :  Iterate until exponent of s(n) < 1.
--             Required to get upper bounds if x>0
--               x : Original parameter from exp(x)
--               y : s(n-1)
--               t : Sum(i=0..n-1, s(i))
--               n : Iteration number. Needed as s(n) = x * s(n-1) / n
--             Note: This may be a *very* slow way of doing this for big x 
--                   exp(6.45) takes 15-16 iterations.
exp_elt1 :: SBinFloat -> SBinFloat -> SBinFloat -> Int
		      -> (SBinFloat,SBinFloat,Int)
exp_elt1 x y@(e,m) t n | e<1       = (y,t,n)
exp_elt1 x y       t n | otherwise = exp_elt1 x y' t' (n+1)
	where {y' = sbfNorm (exp_it x y n);
	       t' = sbfAdd y' t}


-- exp_pos_i : Generate continuation of IReal for x>0
--               x : Original parameter from exp(x) 
--               y : s(n-1)
--               t : Sum(i=0..n-1, s(i))
--               n : Iteration number. Needed as s(n) = x * s(n-1) / n
exp_pos_i :: SBinFloat -> SBinFloat -> SBinFloat -> Int -> IReal
exp_pos_i x y t n = (b: exp_pos_i x y' low (n+1))
	where {y' = exp_it x y n;                 -- Compute s(n)
	       b@(low,upp) = exp_pos_bounds y' t n}   



-- exp_neg_i : Generate continuation of IReal for x<0
--               x : Original parameter from exp(x) 
--               y : s(n-1)
--               t : Sum(i=0..n-1, s(i))
--               n : Iteration number. Needed as s(n) = x * s(n-1) / n
exp_neg_i :: SBinFloat -> SBinFloat -> SBinFloat -> Int -> IReal
exp_neg_i x y t n | odd n      = (b: exp_neg_i x y' low (n+1))
		  | otherwise  = (b: exp_neg_i x y' upp (n+1))
	where {y' = exp_it x y n;
	       b@(low,upp) = exp_neg_bounds y' t n}


-- exp_uk_i : Generate continuation of IReal for sign of x unknown
--               x : Original parameter from exp(x) 
--               y : s(n-1)
--               t : Sum(i=0..n-1, s(i))
--               n : Iteration number. Needed as s(n) = x * s(n-1) / n
exp_uk_i :: SBinFloat -> SBinFloat -> SBinFloat -> Int -> IReal
exp_uk_i x y t n = (b: exp_uk_i x y' t' (n+1))
	where {y' = exp_it x y n;
	       (b@(low,upp),t') = exp_uk_bounds y' t n}


-- exp_pos_iterator : Generate IReal for exp(x) given x>0
--                    First necessary to iterate sequence till s(n) <= 1
exp_pos_iterator :: SBinFloat -> IReal
exp_pos_iterator x = exp_pos_i x y t n
	where (y,t,n) = exp_elt1 x x (sbfAdd sbfOne x) 2


-- exp_neg_iterator : Generate IReal for exp(x) given x<0
exp_neg_iterator :: SBinFloat -> IReal
exp_neg_iterator x = exp_neg_i x x (sbfAdd sbfOne x) 2


-- exp_pos_iterator : Generate IReal for exp(x) given x>0
--                    Assumes that (x <= 1) ==> (s(n) <= 1)
--		      This assumption is safe because we'll only use this
--                    if normalisation reveals x approx. = 0
exp_uk_iterator :: SBinFloat -> IReal
exp_uk_iterator x = exp_uk_i x y t n
	where (y,t,n) = exp_elt1 x x (sbfAdd sbfOne x) 2


sbfExpFn :: SBinFloat -> SBinFloat
sbfExpFn x = case a of 
	    1 ->  sbfLimit (exp_pos_iterator x')
	    0 ->  sbfLimit (exp_uk_iterator  x')
	    -1 -> sbfLimit (exp_neg_iterator x')
	 where x'@(_,(a:_)) = sbfNormMaxOrExp_lte_0 x 10




-- sbfExpon: Exponentiation (ie. x^y)
sbfExpon :: SBinFloat -> SBinFloat -> SBinFloat
sbfExpon x y = sbfExpFn (sbfMul (sbfLn x) y)



